"""
Curated & User-Supplied JSON/CSV Question Dataset Adapter
=========================================================
Parses question bank datasets generated by scripts/build_question_bank.py
or user-uploaded JSON/CSV files into RawQuestion entries using the fixed
11-topic taxonomy and plain-text/Markdown sanitization.
"""

import csv
import io
import json
import time

from src.interviewer.sources.base_source import BaseSource, RawQuestion, ScrapeResult
from src.interviewer.sources.classifier import (
    classify_question,
    classify_round,
    normalize_topic,
)
from src.utils.logger import get_logger
from src.utils.text_utils import strip_html_markup

logger = get_logger(__name__)


class OpenDatasetsSource(BaseSource):
    """Adapter for structured local JSON/CSV question bank datasets."""

    def __init__(self):
        super().__init__("open_dataset", check_robots=False)

    def collect_questions(self, topic: str = "", max_pages: int = 3) -> ScrapeResult:
        """Load questions from the configured local question bank JSON file."""
        import os
        qbank_path = os.getenv("QUESTION_BANK_PATH", "./data/question_bank/questions.json")
        if not os.path.exists(qbank_path):
            return ScrapeResult(questions=[], pages_scraped=0, success=True)
        with open(qbank_path, "r", encoding="utf-8") as f:
            raw_content = f.read()
        questions = self.parse_user_dataset(raw_content, "json")
        if topic.strip():
            tl = topic.strip().lower()
            questions = [q for q in questions if q.topic.lower() == tl]
        return ScrapeResult(
            questions=questions,
            pages_scraped=1 if questions else 0,
            success=True,
        )

    @staticmethod
    def parse_user_dataset(raw_content: str, file_format: str = "json") -> list[RawQuestion]:
        """Parse a JSON or CSV interview dataset into sanitized RawQuestion objects."""
        now = time.time()
        results: list[RawQuestion] = []

        if file_format.lower() == "json":
            data = json.loads(raw_content)
            items = data if isinstance(data, list) else data.get("questions", [])
        elif file_format.lower() == "csv":
            reader = csv.DictReader(io.StringIO(raw_content))
            items = list(reader)
        else:
            raise ValueError(f"Unsupported dataset format: {file_format}")

        for item in items:
            q_text = strip_html_markup(item.get("question_text") or item.get("question") or "")
            if not q_text:
                continue

            raw_topic = item.get("topic") or ""
            inferred_topic, is_tech_inf, inferred_tags = classify_question(
                q_text, item.get("round") or item.get("interview_round") or ""
            )
            topic = normalize_topic(raw_topic, "", q_text) if raw_topic else inferred_topic
            round_val = classify_round(
                q_text, topic, item.get("round") or item.get("interview_round") or ""
            )
            is_tech = (topic != "Behavioral & HR") if "is_technical" not in item else bool(item["is_technical"])

            raw_tags = item.get("tags", [])
            if isinstance(raw_tags, str):
                raw_tags = [strip_html_markup(t).lower() for t in raw_tags.split(",") if t.strip()]
            elif isinstance(raw_tags, list):
                raw_tags = [strip_html_markup(str(t)).lower() for t in raw_tags if str(t).strip()]
            else:
                raw_tags = []

            diff = str(item.get("difficulty") or "medium").strip().lower()
            if diff not in ("easy", "medium", "hard"):
                diff = "medium"

            results.append(RawQuestion(
                question_text=q_text,
                source_url=strip_html_markup(item.get("source_url") or ""),
                role=strip_html_markup(item.get("role") or item.get("job_role") or ""),
                interview_round=round_val,
                topic=topic,
                is_technical=is_tech if topic else is_tech_inf,
                difficulty=diff,
                question_type=str(item.get("question_type") or ("hr" if round_val == "HR" else "open_ended")).strip(),
                reference_answer=strip_html_markup(item.get("reference_answer") or item.get("answer") or ""),
                original_wording=q_text,
                reported_at=strip_html_markup(item.get("reported_at") or ""),
                tags=raw_tags or inferred_tags,
                collected_at=now,
            ))

        return results
